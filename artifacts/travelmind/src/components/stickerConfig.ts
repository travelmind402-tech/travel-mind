export type StickerConfig = {
  id: string;
  /** Transparent PNG path in /public */
  src: string;
  alt: string;
  /** Final docked position, as % of the hero stage (desktop). Use any of top/left/right/bottom. */
  pos: { top?: string; left?: string; right?: string; bottom?: string };
  /** Width in "units": 1 unit = 1vw on desktop (scaled up on tablet/mobile via CSS --u). */
  w: number;
  /** Final tilt in degrees */
  rotate: number;
  /** Final scale (default 1) */
  scale?: number;
  z: number;
  /** Intro state: offset from viewport center in % of stage width/height, plus scale/rotation */
  start: { x: number; y: number; rotate: number; scale: number };
  /** Idle vertical float amplitude in px (small ±4–5, medium ±6–8, large ±8–10) */
  floatY: number;
  /** Optional tiny idle rotation drift in degrees (≤ ±1°) */
  floatRot: number;
  /** Slow idle float cycle duration in seconds (5–8s) */
  floatDur: number;
  /** Negative animation delay in seconds so no two stickers move in sync */
  floatDelay: number;
  /** Scroll parallax depth factor (0.4–1.0: smaller images move less, larger move more) */
  depth: number;
  /** Hide on smaller screens so the layout never crowds the headline */
  hide?: "tablet" | "mobile"; // "tablet" = hidden below 1024px, "mobile" = hidden below 640px
};

